// 1.6 (MTS): layer preview of a part (cross-sections, walls, skin, infill, time per
// layer) and the G-code viewer parser plus the read-only printer file route.
import { test, before, after } from 'node:test';
import assert from 'node:assert/strict';
import { mkdtemp, rm } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { initKernel, createScope } from '../src/core/kernel.js';
import { sliceLayers, hatch } from '../src/core/layers.js';
import { parseGcode, featureOf } from '../public/gcode-parse.js';
import { startServer } from '../src/server.js';
import { startMockMoonraker, MOCK_GCODE } from './helpers/mock-moonraker.js';

let dir, app, base, mock;
before(async () => {
  await initKernel();
  dir = await mkdtemp(join(tmpdir(), 'stltools-v16-'));
  app = await startServer({ host: '127.0.0.1', port: 0, dataDir: dir });
  base = `http://127.0.0.1:${app.address().port}`;
  mock = await startMockMoonraker({ state: 'standby' });
});
after(async () => {
  app.closeAllConnections?.(); app.close();
  mock.server.closeAllConnections?.(); mock.server.close();
  await rm(dir, { recursive: true, force: true });
});
const post = (p, b) => fetch(base + p, { method: 'POST', body: JSON.stringify(b) }).then(async (r) => ({ status: r.status, body: await r.json() }));

test('hatch: lines stay inside the shape, holes are skipped', () => {
  const square = [[0, 0], [10, 0], [10, 10], [0, 10]];
  const hole = [[4, 4], [4, 6], [6, 6], [6, 4]];
  const { segs, len } = hatch([square, hole], 1, 0);
  assert.ok(segs.length > 0);
  for (let i = 0; i < segs.length; i += 2) assert.ok(segs[i] >= -1e-6 && segs[i] <= 10 + 1e-6 && segs[i + 1] >= -1e-6 && segs[i + 1] <= 10 + 1e-6);
  assert.ok(Math.abs(len - (10 * 10 - 2 * 2)) < 2.5, `line length ~ area / spacing (${len})`);
});

test('layer preview: walls, skin at the bottom and top, sparse infill in between, time per layer', () => {
  const k = createScope();
  try {
    const box = k.track(k.Manifold.cube([40, 20, 10]));
    const r = sliceLayers(k, box, { layerHeight: 0.2, walls: 2, shellLayers: 3, infill: 20 }, { nozzle: 0.4, speeds: { outerWall: 50, innerWall: 80, infill: 100, topBottom: 60, firstLayer: 25 }, maxVolumetricFlow: 20 });
    assert.equal(r.layers.length, 50);
    const bottom = r.layers[0], mid = r.layers[25], top = r.layers[49];
    for (const L of [bottom, mid, top]) { assert.equal(L.outer.length, 1, 'one outer wall'); assert.equal(L.inner.length, 1, 'one inner wall'); }
    assert.ok(bottom.skin.length > 0 && bottom.infill.length === 0, 'bottom layer is solid skin');
    assert.ok(top.skin.length > 0, 'top layer is solid skin');
    assert.ok(mid.skin.length === 0 && mid.infill.length > 0, 'middle layer is sparse infill');
    assert.ok(bottom.seconds > mid.seconds, 'solid first layer takes longer');
    assert.ok(Math.abs(bottom.mm.walls - (2 * (40 + 20) - 8 * 0.45 * 0.5) - (2 * (40 + 20) - 8 * 0.45 * 1.5)) < 5, `wall length (${bottom.mm.walls})`);
    assert.ok(r.totals.seconds > 0 && r.totals.filamentMm > 0);
    assert.throws(() => sliceLayers(k, box, { layerHeight: 0.05, maxLayers: 100 }, {}), /more than 100/);
  } finally { k.free(); }
});

test('layer preview API: generated part and options; expired job 404', async () => {
  const g = (await post('/api/generate/sealed-box', {})).body;
  const r = await post('/api/layers', { job: g.job, part: 'lid', layerHeight: 0.3, infill: 10 });
  assert.equal(r.status, 200, JSON.stringify(r.body).slice(0, 200));
  assert.equal(r.body.part, 'lid');
  assert.equal(r.body.layerHeight, 0.3);
  assert.ok(r.body.layers.length >= 10);
  assert.ok(r.body.layers.every((L) => L.outer.length >= 1), 'every layer has an outline');
  assert.equal((await post('/api/layers', { job: 'nope' })).status, 404);
});

test('G-code parser: layers by extruding Z, features from comments, relative E, arcs, header estimate', () => {
  assert.equal(featureOf('External perimeter'), 'outer');
  assert.equal(featureOf('Outer wall'), 'outer');
  assert.equal(featureOf('WALL-INNER'), 'inner');
  assert.equal(featureOf('Sparse infill'), 'infill');
  assert.equal(featureOf('Internal solid infill'), 'skin');
  assert.equal(featureOf('Top surface'), 'skin');
  assert.equal(featureOf('Support interface'), 'support');
  assert.equal(featureOf('Skirt'), 'skirt');
  const g = parseGcode([
    '; generated by OrcaSlicer 2.1.1', '; estimated printing time (normal mode) = 1h 2m 3s', '; layer_height = 0.2',
    'G90', 'M83', 'G1 Z0.2 F600', ';TYPE:Outer wall', 'G1 X10 Y10 F3000', 'G1 X20 Y10 E1', 'G1 X20 Y20 E1',
    ';TYPE:Sparse infill', 'G1 X10 Y20 E1', 'G1 Z0.6 F600', 'G1 X0 Y0', 'G1 Z0.4', '; FEATURE: Inner wall', 'G2 X20 Y0 I10 J0 E2', 'G4 P500',
  ].join('\n'));
  assert.equal(g.layers.length, 2, 'z-hop travel is not a layer');
  assert.deepEqual(g.layers.map((l) => l.z), [0.2, 0.4]);
  assert.equal(g.layers[0].types.outer.length / 4, 2);
  assert.equal(g.layers[0].types.infill.length / 4, 1);
  assert.ok(g.layers[1].types.inner.length / 4 > 20, 'arc split into short lines');
  const ys = [...g.layers[1].types.inner].filter((_, i) => i % 2 === 1);
  assert.ok(Math.max(...ys) > 9.5, 'G2 from (0,0) to (20,0) around (10,0) clockwise goes over the top');
  assert.equal(g.meta.estimatedSeconds, 3723);
  assert.equal(g.meta.layerHeight, 0.2);
  assert.equal(g.totals.filamentMm, 5);
  assert.equal(parseGcode(MOCK_GCODE).meta.slicer.split(' ')[0], 'PrusaSlicer');
});

test('printer G-code file for the viewer: read-only GET, G-code paths only', async () => {
  const pr = (await post('/api/printers', { name: 'SV07', url: `127.0.0.1:${mock.port}`, model: 'sovol-sv07' })).body;
  const before = mock.requests.length;
  const r = await fetch(`${base}/api/printers/${pr.id}/gcode?file=clamp-mount-16_PLA_0.2mm.gcode`);
  assert.equal(r.status, 200);
  assert.equal(await r.text(), MOCK_GCODE);
  assert.equal((await fetch(`${base}/api/printers/${pr.id}/gcode?file=../printer.cfg`)).status, 400);
  assert.ok(mock.requests.slice(before).every((q) => q.method === 'GET'));
});
