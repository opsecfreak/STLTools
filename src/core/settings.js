// App settings, stored on the server in <data>/settings.json so every device
// (desktop, phone on the LAN) sees the same ones.
//
// The SCHEMA below is the single source of truth: every setting has a type,
// a default and limits. GET returns defaults merged with what is saved; PUT
// accepts a partial object (e.g. { viewer: { edges: true } }), checks each
// value against the schema, and ignores unknown keys. No secrets live here:
// printer API keys stay in printers.json and are never sent to browsers.
//
// To add a setting: add it to SCHEMA, use it in the UI (public/settings.js
// draws the form from this schema via /api/settings/schema), add a test.

