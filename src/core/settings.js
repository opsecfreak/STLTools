export function defaults() {
  const out = {};
  for (const [sec, { fields }] of Object.entries(SCHEMA)) {
    out[sec] = {};
    for (const [k, f] of Object.entries(fields)) out[sec][k] = f.default;
  }
  return out;
}

function cleanValue(f, v, name) {
  if (f.type === 'boolean') return Boolean(v);
  if (f.type === 'number' || f.type === 'integer') {
    if ((v === null || v === '') && f.default === null) return null;
    const n = Number(v);
    if (!Number.isFinite(n)) throw new CatalogError(`${name} must be a number`);
    if (n < f.min || n > f.max) throw new CatalogError(`${name} must be from ${f.min} to ${f.max}`);
    return f.type === 'integer' ? Math.round(n) : n;
  }
  if (f.type === 'select') {
    if (!f.options.some(([o]) => o === v)) throw new CatalogError(`${name} must be one of ${f.options.map(([o]) => o).join(', ')}`);
    return v;
  }
  if (f.type === 'color') {
    if (!/^#[0-9a-f]{6}$/i.test(String(v))) throw new CatalogError(`${name} must be a color like #3d8bfd`);
    return String(v).toLowerCase();
  }
  // string / profile
  const s = String(v ?? '').trim();
  if (s.length > (f.maxLength ?? 60)) throw new CatalogError(`${name} is too long`);
  if (f.type === 'profile' && s && !/^[a-z0-9][a-z0-9-]{1,40}$/.test(s)) throw new CatalogError(`${name} is not a profile id`);
  if (f.pattern && !new RegExp(f.pattern).test(s)) throw new CatalogError(`${name} has characters that are not allowed`);
  return s;
}

export function createSettings({ dataDir }) {
  const file = createJsonFile(join(dataDir, 'settings.json'), {});
  const merged = (saved) => {
    const d = defaults();
    for (const sec of Object.keys(d)) Object.assign(d[sec], Object.fromEntries(Object.entries(saved?.[sec] ?? {}).filter(([k]) => k in d[sec])));
    return d;
  };
  return {
    schema: () => SCHEMA,
    async get() {
      return merged(await file.get());
    },
    /** Partial update: { section: { key: value } }. Unknown keys are ignored. */
    async update(patch) {
      if (!patch || typeof patch !== 'object') throw new CatalogError('Settings must be an object');
      const cur = merged(await file.get());
      for (const [sec, values] of Object.entries(patch)) {
        const s = SCHEMA[sec];
        if (!s || !values || typeof values !== 'object') continue;
        for (const [k, v] of Object.entries(values)) {
          if (!s.fields[k]) continue;
          cur[sec][k] = cleanValue(s.fields[k], v, `${s.label}: ${s.fields[k].label}`);
        }
      }
      await file.set(cur);
      return cur;
    },
    async reset(section) {
      const cur = merged(await file.get());
      if (section && SCHEMA[section]) cur[section] = defaults()[section];
      await file.set(section ? cur : {});
      return merged(section ? cur : {});
    },
  };
}
