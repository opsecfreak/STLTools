// G-code parser for the viewer (browser and Node). Reads moves, not machine state:
// G0/G1 (and G2/G3 arcs, split into short lines), G90/G91, M82/M83, G92, G4 dwell,
// feed rates, and the feature comments that slicers write (;TYPE: from PrusaSlicer,
// OrcaSlicer, SuperSlicer and Cura; ; FEATURE: from newer OrcaSlicer).
// A new layer starts when the nozzle extrudes at a higher Z than the current layer
// (z-hops do not count: they do not extrude).
//
// Times are distance / feed rate with no acceleration, so they are lower than the
// slicer's estimate; the slicer's own estimate from the file header is shown next to them.

const FEATURES = [
  ['outer', /outer|external|perimeter.?ext|wall-outer/i],
  ['inner', /inner|perimeter|wall/i],
  ['support', /support/i],
  ['skirt', /skirt|brim|prime/i],
  ['bridge', /bridge/i],
  ['skin', /top|bottom|solid|skin|ironing|gap/i],
  ['infill', /infill|fill/i],
];
export const FEATURE_TYPES = ['outer', 'inner', 'skin', 'infill', 'bridge', 'support', 'skirt', 'other'];

export function featureOf(name) {
  for (const [t, re] of FEATURES) if (re.test(name)) return t;
  return 'other';
}

/** Header / footer facts: slicer, estimated time, filament, layer height. */
export function gcodeMeta(text) {
  const head = text.slice(0, 200000), tail = text.slice(-200000);
  const both = head + '\n' + tail;
  const find = (re) => { const m = both.match(re); return m ? m[1].trim() : null; };
  const toSec = (s) => {
    if (!s) return null;
    if (/^\d+(\.\d+)?$/.test(s)) return Number(s);
    let t = 0;
    for (const [, n, u] of s.matchAll(/(\d+(?:\.\d+)?)\s*([dhms])/g)) t += Number(n) * { d: 86400, h: 3600, m: 60, s: 1 }[u];
    return t || null;
  };
  return {
    slicer: find(/^;\s*generated by\s+(.+)$/im) ?? find(/^;\s*(?:FLAVOR|Generated with)\s*:?\s*(.+)$/im),
    estimatedSeconds: toSec(find(/^;\s*estimated printing time[^=]*=\s*(.+)$/im) ?? find(/^;\s*total estimated time:\s*(.+?)(?:;|$)/im) ?? find(/^;TIME:(\d+)/m)),
    filamentMm: Number(find(/^;\s*filament used \[mm\]\s*=\s*([\d.]+)/im) ?? NaN) || null,
    layerHeight: Number(find(/^;\s*layer_height\s*=\s*([\d.]+)/im) ?? NaN) || null,
  };
}

/**
 * Parse G-code text.
 * -> { layers: [{ z, seconds, extruded, types: { outer: [x1,y1,x2,y2,...], ... }, travel: [...] }], bounds, totals, meta }
 */
export function parseGcode(text, { keepTravel = true, onProgress = null } = {}) {
  const layers = [];
  let x = 0, y = 0, z = 0, e = 0, f = 1800;
  let absXYZ = true, absE = true;
  let feature = 'other';
  let layer = null;
  const bounds = { min: [Infinity, Infinity, Infinity], max: [-Infinity, -Infinity, -Infinity] };
  let seconds = 0, extruded = 0;
  const newLayer = (atZ) => {
    layer = { z: Math.round(atZ * 1000) / 1000, seconds: 0, extruded: 0, types: {}, travel: [] };
    layers.push(layer);
  };
  const seg = (x1, y1, x2, y2, de, len) => {
    if (de > 1e-6) {
      if (!layer || z > layer.z + 1e-3) newLayer(z);
      (layer.types[feature] ??= []).push(x1, y1, x2, y2);
      layer.extruded += de;
      extruded += de;
      if (x2 < bounds.min[0]) bounds.min[0] = x2; if (x2 > bounds.max[0]) bounds.max[0] = x2;
      if (y2 < bounds.min[1]) bounds.min[1] = y2; if (y2 > bounds.max[1]) bounds.max[1] = y2;
      if (z < bounds.min[2]) bounds.min[2] = z; if (z > bounds.max[2]) bounds.max[2] = z;
    } else if (keepTravel && layer && len > 0.01) layer.travel.push(x1, y1, x2, y2);
  };
  const time = (len) => { const t = len / Math.max(0.1, f / 60); seconds += t; if (layer) layer.seconds += t; };
  let pos = 0;
  const n = text.length;
  let lineNo = 0;
  while (pos < n) {
    let end = text.indexOf('\n', pos);
    if (end < 0) end = n;
    const raw = text.slice(pos, end);
    pos = end + 1;
    if (onProgress && (++lineNo & 0x3ffff) === 0) onProgress(pos / n);
    const semi = raw.indexOf(';');
    if (semi >= 0) {
      const c = raw.slice(semi + 1).trim();
      const m = c.match(/^(?:TYPE|FEATURE)\s*:\s*(.+)$/i);
      if (m) feature = featureOf(m[1]);
    }
    const code = (semi >= 0 ? raw.slice(0, semi) : raw).trim().toUpperCase();
    if (!code) continue;
    const word = code.split(/\s+/)[0];
    const arg = (k) => { const m = code.match(new RegExp(`(?:^|\\s)${k}(-?[\\d.]+)`)); return m ? Number(m[1]) : null; };
    if (word === 'G0' || word === 'G1' || word === 'G00' || word === 'G01' || word === 'G2' || word === 'G3' || word === 'G02' || word === 'G03') {
      const nx = arg('X'), ny = arg('Y'), nz = arg('Z'), ne = arg('E'), nf = arg('F');
      if (nf !== null) f = nf;
      const tx = nx === null ? x : absXYZ ? nx : x + nx;
      const ty = ny === null ? y : absXYZ ? ny : y + ny;
      const tz = nz === null ? z : absXYZ ? nz : z + nz;
      const de = ne === null ? 0 : absE ? ne - e : ne;
      if (ne !== null) e = absE ? ne : e + ne;
      const arc = word === 'G2' || word === 'G3' || word === 'G02' || word === 'G03';
      const dz = Math.abs(tz - z);
      z = tz;
      if (arc) {
        const i = arg('I') ?? 0, j = arg('J') ?? 0;
        const cx = x + i, cy = y + j, r = Math.hypot(i, j);
        let a0 = Math.atan2(y - cy, x - cx), a1 = Math.atan2(ty - cy, tx - cx);
        const cw = word === 'G2' || word === 'G02';
        if (cw && a1 >= a0) a1 -= 2 * Math.PI;
        if (!cw && a1 <= a0) a1 += 2 * Math.PI;
        const sweep = a1 - a0;
        const steps = Math.max(2, Math.ceil(Math.abs(sweep) * r / 0.5));
        let px = x, py = y, total = 0;
        for (let s = 1; s <= steps; s++) {
          const a = a0 + (sweep * s) / steps;
          const qx = s === steps ? tx : cx + r * Math.cos(a), qy = s === steps ? ty : cy + r * Math.sin(a);
          const len = Math.hypot(qx - px, qy - py);
          seg(px, py, qx, qy, de / steps, len);
          total += len;
          px = qx; py = qy;
        }
        time(total);
      } else {
        const len = Math.hypot(tx - x, ty - y);
        if (len > 0) seg(x, y, tx, ty, de, len);
        time(Math.max(len, len === 0 ? Math.abs(de) : 0, dz));
      }
      x = tx; y = ty;
    } else if (word === 'G90') absXYZ = true;
    else if (word === 'G91') absXYZ = false;
    else if (word === 'M82') absE = true;
    else if (word === 'M83') absE = false;
    else if (word === 'G92') {
      const ne = arg('E'); if (ne !== null) e = ne;
      const nx = arg('X'); if (nx !== null) x = nx;
      const ny = arg('Y'); if (ny !== null) y = ny;
      const nz = arg('Z'); if (nz !== null) z = nz;
    } else if (word === 'G4') {
      const p = arg('P'), s = arg('S');
      const t = p !== null ? p / 1000 : s ?? 0;
      seconds += t; if (layer) layer.seconds += t;
    }
  }
  for (const L of layers) {
    for (const k of Object.keys(L.types)) L.types[k] = Float32Array.from(L.types[k]);
    L.travel = Float32Array.from(L.travel);
    L.seconds = Math.round(L.seconds * 10) / 10;
    L.extruded = Math.round(L.extruded * 10) / 10;
  }
  if (!layers.length) for (const v of [bounds.min, bounds.max]) v.fill(0);
  return { layers, bounds, totals: { seconds: Math.round(seconds), filamentMm: Math.round(extruded), layers: layers.length }, meta: gcodeMeta(text) };
}
